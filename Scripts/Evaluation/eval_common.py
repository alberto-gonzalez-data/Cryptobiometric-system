def get_hardware_info():
    """
    Captures the runtime environment. Without this, the computational
    timings are neither reproducible nor comparable with other work.
    """
    info = {
        "python":       platform.python_version(),
        "os":           f"{platform.system()} {platform.release()}",
        "machine":      platform.machine(),
        "processor":    platform.processor() or "n/a",
        "cpu_count":    os.cpu_count(),
        "timestamp":    datetime.now().isoformat(),
    }

    # CPU model on Linux
    try:
        with open("/proc/cpuinfo") as f:
            for line in f:
                if line.lower().startswith("model name"):
                    info["cpu_model"] = line.split(":", 1)[1].strip()
                    break
    except Exception:
        pass

    # Total memory
    try:
        import psutil
        info["ram_gb"] = round(psutil.virtual_memory().total / 1024**3, 1)
    except Exception:
        try:
            with open("/proc/meminfo") as f:
                kb = int(f.readline().split()[1])
                info["ram_gb"] = round(kb / 1024**2, 1)
        except Exception:
            info["ram_gb"] = "n/a"

    info.setdefault("cpu_model", info["processor"])
    return info


def hardware_summary(info):
    """A readable one-liner for the report header."""
    return (f"{info.get('cpu_model', 'n/a')} | {info.get('cpu_count', '?')} threads | "
            f"{info.get('ram_gb', '?')} GB RAM | {info.get('os', '')} | "
            f"Python {info.get('python', '')}")


