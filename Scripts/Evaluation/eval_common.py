# 4. EFFECTIVE ENTROPY — DAUGMAN'S DEGREES OF FREEDOM
# ═════════════════════════════════════════════════════════════════

def daugman_degrees_of_freedom(impostor_bers, n_bits):
    """
    Estimates the degrees of freedom (effectively independent bits) of
    the template from the impostor BER distribution:

        DoF = p (1 - p) / sigma^2

    If the n_bits were independent, the impostor BER would follow a
    Binomial(n_bits, 0.5) and DoF ~ n_bits. A DoF well below n_bits would
    indicate correlation between bits and therefore lower effective
    entropy than the nominal figure.

    This is the standard effective-entropy measure in the iris
    literature, and it replaces the "commitment entropy", which is
    circular: delta is random by construction regardless of the
    biometric input.
    """
    b = np.asarray(impostor_bers, dtype=float)
    p = float(np.mean(b))
    v = float(np.var(b))
    dof = p * (1 - p) / v if v > 0 else float("nan")
    return {
        "impostor_ber_mean": round(p, 6),
        "impostor_ber_std":  round(float(np.std(b)), 6),
        "degrees_of_freedom": round(dof, 1),
        "n_bits_nominal":    int(n_bits),
        "dof_ratio":         round(dof / n_bits, 3) if n_bits else None,
        "n_comparisons":     int(b.size),
        "note": ("DoF ~ n_bits indicates statistically independent bits. "
                 "The real security ceiling is min(DoF, secret bits)."),
    }


