def clopper_pearson(k, n, alpha=0.05):
    """
    Exact (binomial) confidence interval for a proportion.
    Also valid when k = 0 or k = n, unlike the normal approximation.
    Returns (lower_bound, upper_bound) in [0, 1].
    """
    if n == 0:
        return 0.0, 1.0
    lo = 0.0 if k == 0 else _beta_dist.ppf(alpha / 2, k, n - k + 1)
    hi = 1.0 if k == n else _beta_dist.ppf(1 - alpha / 2, k + 1, n - k)
    return float(lo), float(hi)


def rate_with_ci(k, n, alpha=0.05):
    """
    Packages an observed rate with its exact CI, as a percentage.

    For the k=0 case, the upper bound is the useful figure: with 0
    successes out of n attempts, a zero rate CANNOT be claimed — only
    "below ci_high_pct at 95% confidence".
    """
    rate = (k / n * 100) if n > 0 else 0.0
    lo, hi = clopper_pearson(k, n, alpha)
    return {
        "rate_pct":     round(rate, 4),
        "successes":    int(k),
        "trials":       int(n),
        "ci_low_pct":   round(lo * 100, 6),
        "ci_high_pct":  round(hi * 100, 6),
        "ci_level":     1 - alpha,
    }


def format_rate(r, decimals=2):
    """Formats a rate with its CI for report tables."""
    if r["trials"] == 0:
        return "n/a"
    if r["successes"] == 0:
        return f"0 ({r['trials']:,} trials, 95% CI < {r['ci_high_pct']:.4f}%)"
    return (f"{r['rate_pct']:.{decimals}f}% "
            f"[{r['ci_low_pct']:.{decimals}f}\u2013{r['ci_high_pct']:.{decimals}f}] "
            f"(n={r['trials']:,})")


def format_rate_compact(r, decimals=4):
    """
    Compact version of format_rate() for dense tables (many columns),
    where the full format_rate() output ("0 (500 trials, 95% CI < X%)")
    is too wide and visually overflows into the next column.

    Omits the trial count (n) -- put it in the table caption or a nearby
    sentence instead, since it usually repeats across every row of a
    sweep. Uses a plain hyphen rather than an en-dash for maximum
    compatibility with any downstream tooling.
    """
    if r["trials"] == 0:
        return "n/a"
    if r["successes"] == 0:
        return f"< {r['ci_high_pct']:.{decimals}f}%"
    return (f"{r['rate_pct']:.{decimals}f}% "
            f"[{r['ci_low_pct']:.{decimals}f}-{r['ci_high_pct']:.{decimals}f}]")


def effective_security_bits(far_rate):
    """
    Effective security against the false accept attack: -log2(FAR).

    Computed from the UPPER bound of the CI, which is the only defensible
    figure when no false acceptances have been observed. With only 1000
    attempts, the demonstrated security is ~8 bits, not the 128 bits of
    the secret: that distinction is exactly what a security
    analysis must make explicit.
    """
    p_hi = far_rate["ci_high_pct"] / 100.0
    if p_hi <= 0:
        return None
    return round(float(-np.log2(p_hi)), 2)


