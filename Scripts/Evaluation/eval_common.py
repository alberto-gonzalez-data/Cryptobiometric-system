def filter_subjects_with_min_images(enroll_by_class, test_by_class,
                                    n_enroll, n_verify):
    """
    Excludes from the evaluation any subject that does not have at least
    n_enroll enrollment images AND at least n_verify verification images.

    Rationale: the enroll/test split is generated by dividing 50/50
    (rounded) the TOTAL number of images available per identity in the
    source dataset (05_extract_features.py). An identity with few
    captures at the source receives few on both sides of the split, and
    the evaluation code (embs[:n_enroll]) silently uses fewer images
    than declared, without any warning or failure.

    Applying this filter BEFORE evaluation guarantees that the reported
    subject count accurately describes "N subjects, each with n_enroll
    enrollment images and at least n_verify verification images" —
    literally true for the resulting subset, rather than an approximate
    figure with silent exceptions.

    Returns (filtered_enroll, filtered_test, stats), where stats includes
    a breakdown of how many subjects were excluded and why, so it is
    documented in the report rather than lost.
    """
    all_classes = set(enroll_by_class.keys()) | set(test_by_class.keys())

    missing_enroll = {c for c in all_classes if c not in enroll_by_class}
    missing_test   = {c for c in all_classes if c not in test_by_class}
    short_enroll = {c: len(enroll_by_class[c]) for c in enroll_by_class
                    if len(enroll_by_class[c]) < n_enroll}
    short_test   = {c: len(test_by_class[c]) for c in test_by_class
                    if len(test_by_class[c]) < n_verify}

    excluded = (missing_enroll | missing_test |
                set(short_enroll) | set(short_test))

    enroll_filtered = {c: v for c, v in enroll_by_class.items()
                       if c not in excluded}
    test_filtered = {c: v for c, v in test_by_class.items()
                     if c not in excluded}

    stats = {
        "n_subjects_before":       len(all_classes),
        "n_subjects_after":        len(enroll_filtered),
        "n_excluded":              len(excluded),
        "n_excluded_enroll_short": len(short_enroll),
        "n_excluded_test_short":   len(short_test),
        "n_excluded_missing_split": len(missing_enroll | missing_test),
        "example_excluded": [
            {"subject": c, "n_enroll_available": len(enroll_by_class.get(c, [])),
             "n_test_available": len(test_by_class.get(c, []))}
            for c in list(excluded)[:5]
        ],
        "n_enroll_required": n_enroll,
        "n_verify_required": n_verify,
        "note": ("Subjects excluded for not meeting the declared minimum "
                 f"of {n_enroll} enrollment images and {n_verify} "
                 "verification images. See 'example_excluded' for examples."),
    }
    return enroll_filtered, test_filtered, stats


def save_json(obj, path):
    """Saves JSON, converting numpy types."""
    def _default(o):
        if isinstance(o, (np.integer,)):
            return int(o)
        if isinstance(o, (np.floating,)):
            return float(o)
        if isinstance(o, (np.ndarray,)):
            return o.tolist()
        if isinstance(o, (np.bool_,)):
            return bool(o)
        return str(o)
    with open(str(path), "w") as f:
        json.dump(obj, f, indent=2, default=_default)
    return str(path)
