# 5. UNLINKABILITY — GOMEZ-BARRERO et al. (2018)
# ═════════════════════════════════════════════════════════════════

def unlinkability_gomez_barrero(mated_scores, unmated_scores,
                                n_bins=None, omega=1.0):
    """
    Unlinkability metric from the framework of Gomez-Barrero et al.,
    IEEE TIFS 2018, "General framework to evaluate unlinkability in
    biometric template protection systems".

    For each score value s, the likelihood ratio
    LR(s) = p(s | H_m) / p(s | H_nm) is computed, and from it the local
    measure

        D(s) = 2 * omega * LR(s) / (1 + omega * LR(s)) - 1,  bounded to [0,1]

    D_sys is the mean of D(s) weighted by the mated distribution.

    Interpretation:
        D_sys = 0  -> fully unlinkable system
        D_sys = 1  -> fully linkable system

    Note: not to be confused with the D_sys previously computed by this
    script, which was an effect size (Cohen's d) with a 0.1 threshold and
    a different scale.
    """
    m  = np.asarray(mated_scores,  dtype=float)
    nm = np.asarray(unmated_scores, dtype=float)

    # The number of bins must scale with the sample size. Too many bins
    # produce cells where p_nm=0 and p_m>0 purely from sampling noise,
    # which yields LR=infinity and an artificial D_sys floor above zero
    # even for a perfectly unlinkable system.
    if n_bins is None:
        n_bins = int(np.clip(min(m.size, nm.size) // 25, 10, 60))

    lo = float(min(m.min(), nm.min()))
    hi = float(max(m.max(), nm.max()))
    if hi <= lo:
        hi = lo + 1e-9
    edges = np.linspace(lo, hi, n_bins + 1)

    h_m,  _ = np.histogram(m,  bins=edges)
    h_nm, _ = np.histogram(nm, bins=edges)
    p_m  = h_m  / h_m.sum()  if h_m.sum()  > 0 else h_m
    p_nm = h_nm / h_nm.sum() if h_nm.sum() > 0 else h_nm

    d_local = np.zeros(n_bins, dtype=float)
    for i in range(n_bins):
        if p_m[i] <= 0:
            continue
        if p_nm[i] <= 0:
            d_local[i] = 1.0            # LR -> infinity
        else:
            lr = p_m[i] / p_nm[i]
            d_local[i] = np.clip(2 * omega * lr / (1 + omega * lr) - 1, 0.0, 1.0)

    d_sys = float(np.sum(p_m * d_local))
    centers = 0.5 * (edges[:-1] + edges[1:])

    # With few samples an artificial floor appears: cells where the
    # non-mated distribution has no mass purely by chance contribute
    # D(s)=1.
    n_min = min(m.size, nm.size)
    adequate = n_min >= 250

    return {
        "D_sys_gomez_barrero": round(d_sys, 6),
        "sample_adequate": bool(adequate),
        "sample_warning": (None if adequate else
            f"Only {n_min} comparisons per distribution. D_sys shows an "
            f"artificial floor from sampling noise with n < 250; use at "
            f"least 250-500 users for a publishable value."),
        "D_local_max":         round(float(d_local.max()), 6),
        "verdict":             "UNLINKABLE" if d_sys < 0.1 else "LINKABLE",
        "n_mated":             int(m.size),
        "n_unmated":           int(nm.size),
        "omega":               omega,
        "n_bins":              n_bins,
        "reference": ("Gomez-Barrero et al., IEEE TIFS 2018. "
                      "D_sys in [0,1]; 0 = unlinkable."),
    }, centers, d_local


def cohens_d(a, b):
    """
    Effect size between two distributions. This is what the previous
    version of the script called (incorrectly) D_sys. Kept to allow
    comparison with prior results, but under its correct name.
    """
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    s = np.sqrt(0.5 * (a.var() + b.var()) + 1e-12)
    return round(float(abs(a.mean() - b.mean()) / s), 6)


