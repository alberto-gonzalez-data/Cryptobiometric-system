# 6. ANALYTICAL REED-SOLOMON DECODING MODEL
# ═════════════════════════════════════════════════════════════════

def expected_byte_errors(ber, n_bits):
    """
    Expected number of erroneous BYTES given a BIT-level BER.

    Reed-Solomon corrects byte errors, not bit errors. A byte is
    corrupted as soon as a single one of its 8 bits is wrong, so RS
    efficiency drops quickly when errors are scattered:

        P(byte error) = 1 - (1 - BER)^8

    This is the quantitative reason BCH is proposed as future work: it
    corrects directly at the bit level and does not suffer this loss.
    """
    n_bytes = n_bits // 8
    q = 1 - (1 - ber) ** 8
    return {
        "ber":                  round(float(ber), 6),
        "bit_errors":           round(float(ber * n_bits), 2),
        "p_byte_error":         round(float(q), 6),
        "expected_byte_errors": round(float(q * n_bytes), 2),
        "n_bytes":              n_bytes,
    }


def rs_decode_probability(ber, n_bits, n_parity):
    """P(RS decodes) for a given BER, byte-level binomial model."""
    n_bytes = n_bits // 8
    t = n_parity // 2
    q = 1 - (1 - ber) ** 8
    return float(_binom.cdf(t, n_bytes, q))


def analytical_far(impostor_bers, n_bits, n_parity, n_grid=4000):
    """
    Analytical FAR from the impostor BER distribution.

    Counting false acceptances directly is very insensitive: with 1000
    attempts and 0 successes only FAR < 0.3% can be claimed. Modeling
    the decoding probability over the measured impostor BER distribution
    gives several orders of magnitude more resolution.

    Two estimates are returned:
      - empirical: mean of P(decodes) over the observed impostor BERs
      - gaussian: integrates over a normal distribution fitted to those
        BERs, which correctly extrapolates the lower tail (the one that
        produces false acceptances) beyond the observed minimum

    Both are UPPER BOUNDS on the real FAR, because a successful but
    incorrect RS decode still has to pass Argon2 verification, which
    will reject it.
    """
    b = np.asarray(impostor_bers, dtype=float)
    n_bytes = n_bits // 8
    t = n_parity // 2

    q_emp = 1 - (1 - b) ** 8
    far_emp = float(np.mean(_binom.cdf(t, n_bytes, q_emp)))

    mu, sd = float(b.mean()), float(b.std())
    grid = np.linspace(max(0.0, mu - 8 * sd), min(1.0, mu + 8 * sd), n_grid)
    pdf = np.exp(-0.5 * ((grid - mu) / sd) ** 2) / (sd * np.sqrt(2 * np.pi))
    pdf = pdf / _trapz(pdf, grid)
    q_g = 1 - (1 - grid) ** 8
    far_gauss = float(_trapz(pdf * _binom.cdf(t, n_bytes, q_g), grid))

    def _sec(p):
        return round(float(-np.log2(p)), 1) if p > 0 else None

    # Validity check for the gaussian model. If the observed minimum is
    # many sigmas from the mean, the real lower tail is much heavier
    # than a normal distribution and the gaussian estimate underestimates
    # the FAR by several orders of magnitude. In that case the honest
    # estimate is the empirical one, and it is worth investigating the
    # closest pairs: an anomalously low impostor BER usually indicates
    # that the impostor set contains comparisons that are not zero-effort
    # (for example, the same subject registered under two identities, or
    # cross-spectral captures of the same eye treated as separate
    # classes).
    z_min = (mu - float(b.min())) / sd if sd > 0 else 0.0
    gauss_valid = z_min < 5.0

    return {
        "far_analytic_empirical":  far_emp,
        "far_analytic_gaussian":   far_gauss,
        "gaussian_model_valid":    bool(gauss_valid),
        "min_ber_z_score":         round(float(z_min), 1),
        "recommended_estimate":    ("gaussian" if gauss_valid else "empirical"),
        "gaussian_warning": (None if gauss_valid else
            f"The minimum observed impostor BER is {z_min:.1f} sigmas from "
            f"the mean: the lower tail is not gaussian and the normal model "
            f"underestimates the FAR. Use the empirical estimate and review "
            f"the closest impostor pairs."),
        "security_bits_empirical": _sec(far_emp),
        "security_bits_gaussian":  _sec(far_gauss),
        "impostor_ber_mean":       round(mu, 6),
        "impostor_ber_std":        round(sd, 6),
        "impostor_ber_min":        round(float(b.min()), 6),
        "n_impostor_samples":      int(b.size),
        "t_bytes_correctable":     t,
        "note": ("Upper bound: an incorrect RS decode must still pass "
                 "Argon2. This complements the counted FAR rather than "
                 "replacing it."),
    }


def closest_impostor_pairs(impostor_records, k=10):
    """
    Lists the impostor pairs with the lowest BER.

    A correct zero-effort impostor set should have its BER concentrated
    around ~0.5. Anomalously low values almost always indicate a
    protocol issue rather than a system weakness: the same subject
    registered under two identifiers, or captures of the same eye in
    different spectra treated as separate classes. These pairs inflate
    the estimated FAR and should be identified before interpreting the
    security results.

    Args:
        impostor_records: list of (ber, query_class, target_class)
    """
    if not impostor_records:
        return {"pairs": [], "n": 0}

    ordered = sorted(impostor_records, key=lambda r: r[0])[:k]
    pairs = [{"ber": round(float(b), 6), "query_class": str(q),
              "target_class": str(t),
              "same_dataset": str(q).split("_")[0] == str(t).split("_")[0]}
             for b, q, t in ordered]

    bers = np.array([r[0] for r in impostor_records], dtype=float)
    mu, sd = float(bers.mean()), float(bers.std())
    suspicious = [p for p in pairs
                  if sd > 0 and (mu - p["ber"]) / sd > 5.0]

    return {
        "pairs":            pairs,
        "n":                len(impostor_records),
        "n_suspicious":     len(suspicious),
        "suspicious_pairs": suspicious,
        "note": ("Pairs with a BER more than 5 sigmas below the impostor "
                 "mean. Check whether they correspond to the same subject "
                 "under different identities before interpreting them as a "
                 "weakness of the scheme."),
    }


