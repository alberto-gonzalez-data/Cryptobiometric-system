"""
eval_common.py
Shared utilities for the evaluation scripts.

This module centralizes everything the four reports need in common:

  1. Reproducibility      — deterministic enrollment with a seeded RNG
  2. Statistics           — exact confidence intervals (Clopper-Pearson)
  3. Environment           — hardware capture for reproducibility
  4. Effective entropy     — Daugman's degrees of freedom
  5. Unlinkability         — D_sys metric from Gomez-Barrero et al. (2018)
  6. Analytical FAR        — byte-level RS decoding model
  7. Attacks               — template inversion, index linkage,
                             cross-matching between revoked templates

Rationale for each block:

  (1) By default enroll_user() in 07_fuzzy_commitment draws the transform
      seed and the secret from secrets.token_hex() and os.urandom(), which
      are not seedable. That makes two runs of the same experiment produce
      different GAR values (~0.2 pp of variation). For reproducible results
      the evaluation calls the same enroll_user() passing a seeded
      np.random.Generator (enroll_user_seeded).
      IMPORTANT: this is ONLY for evaluation. Production must always call
      enroll_user() without rng, with real entropy.

  (2) Reporting "FAR = 0.0000%" from 500 or 1000 attempts implies a
      resolution of 1e-6 that was never actually measured. With 0
      successes out of n attempts, the 95% CI upper bound is
      approximately 3/n (rule of three). All rates are now reported as
      k/n with an exact CI.

  (4) The commitment "entropy" that was measured before is circular:
      since delta = xc XOR c and c derives from a random secret, the
      fraction of ones being ~0.5 is guaranteed by construction and the
      metric cannot fail. Daugman's degrees of freedom, estimated from
      the impostor distribution, do measure real effective entropy.

  (5) The D_sys that was previously computed was an effect size
      (Cohen's d), not the D_sys from the literature. The standard is
      Gomez-Barrero et al., "General framework to evaluate unlinkability
      in biometric template protection systems", IEEE TIFS 2018, based
      on the likelihood ratio, ranging over [0, 1]. Both are implemented
      here, and the old one is renamed to avoid a name collision.

Usage:
    import importlib
    _ec = importlib.import_module("eval_common")
"""

