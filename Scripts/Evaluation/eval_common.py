def recover_cancelable_transform(n_bits, user_id, seed):
    """
    Recovers the cancelable transform by probing, without knowledge of
    its internal implementation.

    The transform is applied to the zero vector to obtain a possible
    XOR mask, and then to each vector of the canonical basis to locate
    which position each bit maps to. Works whether the transform is a
    pure permutation or a permutation + XOR.

    Cost: n_bits + 1 calls. For n_bits=256 this is instantaneous.
    """
    zero = np.zeros(n_bits, dtype=np.uint8)
    mask = np.asarray(apply_cancelable_transform(zero, user_id, seed),
                      dtype=np.uint8)

    perm = np.full(n_bits, -1, dtype=int)
    for i in range(n_bits):
        e = np.zeros(n_bits, dtype=np.uint8)
        e[i] = 1
        out = np.asarray(apply_cancelable_transform(e, user_id, seed),
                         dtype=np.uint8) ^ mask
        nz = np.flatnonzero(out)
        if nz.size:
            perm[i] = int(nz[0])
    return perm, mask


def invert_cancelable(xc, perm, mask):
    """Reverses the cancelable transform given the permutation and mask."""
    x = np.zeros(len(perm), dtype=np.uint8)
    for i, j in enumerate(perm):
        if j >= 0:
            x[i] = xc[j] ^ mask[j]
    return x


def attack_template_inversion(enroll_by_class, n_bits, n_users, rng):
    """
    TEMPLATE INVERSION ATTACK.

    Full database compromise scenario: the attacker has the complete
    record T = (delta, h(s), reliable_indices, transform_seed) and
    complete knowledge of the algorithm.

    Two cases are compared:
      (a) With the transform_seed stored in the record.
      (b) With an incorrect transform_seed (control).

    In (a) the cancelable transform is a permutation, and therefore
    bijective: given the seed, xc -> x is exact. Since the reliable
    indices are also stored, the attacker additionally recovers which
    embedding dimensions each bit corresponds to.

    This does NOT mean the system is broken: the commitment delta still
    protects the secret. What it measures is that, under the threat
    model assumed here (full database compromise), non-invertibility CANNOT rest on the
    cancelable layer if the seed is stored in the clear alongside the
    template.
    """
    classes = list(enroll_by_class.keys())[:n_users]
    ber_with_seed, ber_wrong_seed, exact = [], [], 0

    for cls in classes:
        embs = enroll_by_class[cls]
        seed = rng.bytes(32).hex()

        mean_emb = np.mean(np.array(embs), axis=0)
        norm = np.linalg.norm(mean_emb)
        if norm > 0:
            mean_emb = mean_emb / norm

        indices = select_reliable_bits(mean_emb, n_bits)
        x_true  = binarize(mean_emb[indices])
        xc      = apply_cancelable_transform(x_true, cls, seed)

        perm, mask = recover_cancelable_transform(n_bits, cls, seed)
        x_rec = invert_cancelable(np.asarray(xc, dtype=np.uint8), perm, mask)
        d = hamming_distance(x_rec, x_true)
        ber_with_seed.append(d)
        if d == 0.0:
            exact += 1

        wrong = rng.bytes(32).hex()
        p2, m2 = recover_cancelable_transform(n_bits, cls, wrong)
        x_bad = invert_cancelable(np.asarray(xc, dtype=np.uint8), p2, m2)
        ber_wrong_seed.append(hamming_distance(x_bad, x_true))

    n = len(classes)
    return {
        "n_users":                    n,
        "ber_with_stored_seed":       round(float(np.mean(ber_with_seed)), 6),
        "ber_with_wrong_seed":        round(float(np.mean(ber_wrong_seed)), 6),
        "exact_recovery_rate_pct":    round(exact / n * 100, 2) if n else 0.0,
        "transform_probe_cost_calls": n_bits + 1,
        "interpretation": (
            "With the transform_seed stored, recovery of the binary "
            "template is exact (BER=0). With an incorrect seed the BER is "
            "~0.5. Non-invertibility therefore depends on the "
            "confidentiality of the seed, not on the transform itself."),
    }


def attack_index_linkage(enroll_by_class, n_bits, n_users, rng, emb_dim=None):
    """
    RELIABLE-INDEX LINKAGE ATTACK.

    select_reliable_bits() picks the n_bits components with the largest
    |value| of the enrollment mean. It depends ONLY on the embedding, not
    on the transform_seed. Since the indices are stored in the record,
    two "revoked" templates of the same user share the same list.

    Three scenarios are measured with the Jaccard index between sets:

      A. Revocation without a new capture (the nominal definition of
         revocability: a new template without a new acquisition).
         Same embeddings, different seed.
      B. Re-enrollment with different captures of the same user.
      C. Different users (baseline).

    If A or B sit well above C, the unlinkability measured over the bit
    vectors does not hold for the full stored record, which is what an
    attacker actually sees.
    """
    def _indices(embs):
        m = np.mean(np.array(embs), axis=0)
        nrm = np.linalg.norm(m)
        if nrm > 0:
            m = m / nrm
        return set(select_reliable_bits(m, n_bits).tolist())

    def _jaccard(a, b):
        return len(a & b) / len(a | b) if (a | b) else 0.0

    classes = list(enroll_by_class.keys())[:n_users]
    j_same_capture, j_recapture, j_diff_user = [], [], []

    for cls in classes:
        embs = enroll_by_class[cls]
        idx_full = _indices(embs)

        # A. same capture, revoked seed -> the indices do not change
        j_same_capture.append(_jaccard(idx_full, _indices(embs)))

        # B. re-enrollment with disjoint halves of the captures
        if len(embs) >= 4:
            half = len(embs) // 2
            j_recapture.append(_jaccard(_indices(embs[:half]),
                                        _indices(embs[half:])))

    all_classes = list(enroll_by_class.keys())
    for _ in range(min(500, max(len(classes) * 5, 50))):
        c1 = rng.choice(all_classes)
        c2 = rng.choice([c for c in all_classes if c != c1])
        j_diff_user.append(_jaccard(_indices(enroll_by_class[c1]),
                                    _indices(enroll_by_class[c2])))

    dim = emb_dim if emb_dim else 2048
    baseline = (n_bits * n_bits / dim) / (2 * n_bits - n_bits * n_bits / dim)

    def _stat(v, note):
        if not v:
            return {"jaccard_mean": None, "n": 0, "note": note}
        return {"jaccard_mean": round(float(np.mean(v)), 6),
                "jaccard_std":  round(float(np.std(v)), 6),
                "n": len(v), "note": note}

    res = {
        "same_capture_revoked_seed": _stat(
            j_same_capture, "Revocation without a new capture (limiting case)"),
        "re_enrolment_new_captures": _stat(
            j_recapture, "Re-enrollment with different captures"),
        "different_users": _stat(
            j_diff_user, "Baseline: different users"),
        "jaccard_baseline_random": round(float(baseline), 6),
        "n_bits": n_bits, "embedding_dim": dim,
    }

    a = res["same_capture_revoked_seed"]["jaccard_mean"]
    c = res["different_users"]["jaccard_mean"]
    res["linkable_via_indices"] = bool(
        a is not None and c is not None and a > c + 0.2)
    res["interpretation"] = (
        "The reliable indices are derived from the embedding, not the "
        "seed. If the Jaccard overlap of revoked templates from the same "
        "user is clearly above the baseline, the stored record allows "
        "identities to be linked even though the bit vectors themselves "
        "are uncorrelated.")
    return res


def attack_cross_matching(enroll_by_class, n_bits, n_parity, n_users, rng):
    """
    CROSS-MATCHING ATTACK BETWEEN REVOKED TEMPLATES
    (cross-matching experiments to ensure that previously compromised
    templates cannot be used to link or infer newly generated ones).

    For each user, two records are generated with different seeds: T_A
    (compromised) and T_B (new, after revocation). Two attacks are
    tested:

      1. Naive attack: use the old cancelable template xc_A directly
         against the new commitment delta_B.
         Expected: failure (~0% success).

      2. Informed attack: the attacker who compromised the database
         knows both seed_A and seed_B, since both are stored in the
         clear. Inverts xc_A with seed_A, reapplies the transform with
         seed_B, and attacks delta_B.
         Expected: success, if the seed is not protected separately.

    The difference between 1 and 2 is exactly the measure of how much
    protection revocation provides against a full database compromise.
    """
    classes = list(enroll_by_class.keys())[:n_users]
    naive_ok, informed_ok, total = 0, 0, 0

    for cls in classes:
        embs = enroll_by_class[cls]

        rec_A = enroll_user_seeded(embs, cls, n_bits, n_parity, rng)
        rec_B = enroll_user_seeded(embs, cls, n_bits, n_parity, rng)

        idx_A = np.array(rec_A["reliable_indices"])
        mean_emb = np.mean(np.array(embs), axis=0)
        nrm = np.linalg.norm(mean_emb)
        if nrm > 0:
            mean_emb = mean_emb / nrm

        xc_A = verify_template_reliable(mean_emb, cls, rec_A["transform_seed"], idx_A)

        cd_B = {"commitment":  rec_B["commitment"],
                "hash_secret": rec_B["hash_secret"],
                "n_parity":    n_parity}

        # 1. naive
        ok1, _, _ = verify_commitment(np.asarray(xc_A, dtype=np.uint8), cd_B)

        # 2. informed: invert with seed_A, reapply with seed_B
        perm, mask = recover_cancelable_transform(n_bits, cls, rec_A["transform_seed"])
        x_plain = invert_cancelable(np.asarray(xc_A, dtype=np.uint8), perm, mask)
        xc_B = apply_cancelable_transform(x_plain, cls, rec_B["transform_seed"])
        ok2, _, _ = verify_commitment(np.asarray(xc_B, dtype=np.uint8), cd_B)

        total += 1
        naive_ok    += int(bool(ok1))
        informed_ok += int(bool(ok2))

    return {
        "n_users": total,
        "naive_cross_match":    rate_with_ci(naive_ok, total),
        "informed_cross_match": rate_with_ci(informed_ok, total),
        "interpretation": (
            "The naive attack must always fail. If the informed attack "
            "succeeds, revocation does not protect against a full "
            "database compromise as long as the transform_seed is stored "
            "alongside the protected template."),
    }


def secret_reconstruction_cost(n_bits, n_parity, argon2_ms=14.0):
    """
    SECRET RECONSTRUCTION ATTACK.

    Analytical cost of the two paths available to the attacker:

      1. Exhaustive search of the secret: 2^(secret_bits) Argon2
         evaluations. Infeasible by design.

      2. Structural leakage of the commitment: since delta = x XOR c and
         c belongs to the Reed-Solomon code, which has 2^(secret_bits)
         codewords within a space of 2^(n_bits), the template x is
         confined to a coset of that size. That is, delta leaks
         (n_bits - secret_bits) bits of information about x. This is the
         classic fuzzy commitment leakage and should be stated
         explicitly.
    """
    secret_bits = (n_bits // 8 - n_parity) * 8
    years = (2 ** secret_bits) * (argon2_ms / 1000) / (3600 * 24 * 365)
    return {
        "secret_bits":              secret_bits,
        "brute_force_evaluations":  f"2^{secret_bits}",
        "argon2_ms_per_eval":       argon2_ms,
        "brute_force_years_single_core": f"{years:.3e}",
        "template_bits":            n_bits,
        "coset_size":               f"2^{secret_bits}",
        "structural_leakage_bits":  n_bits - secret_bits,
        "note": ("delta confines x to a coset of the RS code of size "
                 f"2^{secret_bits} within 2^{n_bits}: a structural leakage "
                 f"of {n_bits - secret_bits} bits about the template. This "
                 "is inherent to fuzzy commitment and should be reported "
                 "explicitly."),
    }


